import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_EXECUTABLE });
const page = await browser.newPage({ viewport: { width: 1365, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const base = process.env.DEMO_URL || 'http://127.0.0.1:4187';
const output = new URL('../docs/verification/browser/', import.meta.url);
await mkdir(output, { recursive: true });
try {
  await page.goto(base);
  await page.getByRole('heading', { name: 'Today, Alex Demo' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Phone view', exact: true }).getAttribute('aria-pressed'), 'true');
  await page.screenshot({ path: fileURLToPath(new URL('00-today-phone.png', output)), fullPage: true });
  await page.getByRole('button', { name: 'Wide view', exact: true }).click();
  await page.screenshot({ path: fileURLToPath(new URL('01-today-desktop.png', output)), fullPage: true });
  await page.getByRole('button', { name: 'Phone view', exact: true }).click();
  await page.getByRole('button', { name: 'Add expense', exact: true }).click();
  await page.getByRole('button', { name: 'Save expense' }).click();
  await page.getByRole('alert').filter({ hasText: 'Enter a positive amount' }).waitFor();
  await page.getByLabel('Amount (EUR)').fill('0,29');
  await page.getByLabel('Note (optional)').fill('Browser regression coffee');
  await page.getByLabel('Recurring expense').check();
  await page.getByRole('button', { name: 'Save expense' }).click();
  await page.getByText('Browser regression coffee', { exact: true }).waitFor();
  await page.screenshot({ path: fileURLToPath(new URL('02-finance-saved.png', output)), fullPage: true });
  await page.reload();
  await page.getByText('Browser regression coffee', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Delete Browser regression coffee' }).click();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(await page.getByText('Browser regression coffee', { exact: true }).count(), 1);
  await page.getByRole('button', { name: 'Delete Browser regression coffee' }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete', exact: true }).click();
  await page.getByText('Browser regression coffee', { exact: true }).waitFor({ state: 'detached' });
  assert.equal(await page.getByText('Browser regression coffee', { exact: true }).count(), 0);

  await page.goto(base + '/#onboarding');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByText('Enter a name and an age', { exact: false }).waitFor();
  await page.getByLabel('Your name').fill('Taylor Demo');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByLabel('Monthly budget (optional)').fill('100');
  await page.getByLabel('Food budget (optional)').fill('101');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.locator('#setup-error').filter({ hasText: 'Food budget must not exceed the monthly budget.' }).waitFor();
  await page.getByLabel('Food budget (optional)').fill('50');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByRole('button', { name: 'Finish setup' }).click();
  await page.getByRole('heading', { name: 'Today, Taylor Demo' }).waitFor();
  await page.goto(base + '/#settings');
  await page.getByLabel('Dark mode').check();
  await page.getByLabel('Currency for new expenses and totals').selectOption('USD');
  await page.getByRole('button', { name: 'Save preferences' }).click();
  await page.reload();
  assert.equal(await page.getByLabel('Dark mode').isChecked(), true);
  assert.equal(await page.getByLabel('Currency for new expenses and totals').inputValue(), 'USD');
  await page.screenshot({ path: fileURLToPath(new URL('03-settings-dark.png', output)), fullPage: true });
  for (const route of ['today', 'finance', 'nutrition', 'workout', 'grocery', 'mentalhealth', 'habits', 'analytics', 'profile', 'settings']) {
    await page.goto(base + '/#' + route);
    assert.equal(await page.locator('h1').count(), 1);
  }
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto(base + '/#finance');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: fileURLToPath(new URL('04-finance-mobile.png', output)), fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS: setup validation, exact-cent expense lifecycle, deletion cancel/confirm, reload persistence, currency, dark mode, all 10 destinations, 375px layout, no browser errors.');
} finally { await browser.close(); }
